use std::collections::BTreeMap;

/// Declares the struct and a private all-zero constructor from one field list.
/// There is deliberately no public `Default`: a zero config would not hash like C#.
macro_rules! config_fields {
    ($($name:ident: $ty:ty,)*) => {
        /// Tunable numbers loaded from `config.csv`; every key has a code default.
        #[derive(Clone, Debug, PartialEq)]
        pub struct SimulationConfig {
            $(pub $name: $ty,)*
            pub(super) effective: BTreeMap<String, String>,
        }

        impl SimulationConfig {
            /// Every field zero; the starting point for `code_defaults`.
            pub(super) fn zeroed() -> Self {
                Self {
                    $($name: Default::default(),)*
                    effective: BTreeMap::new(),
                }
            }
        }
    };
}

